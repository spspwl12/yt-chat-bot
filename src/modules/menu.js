// 전체 메뉴 풀 (총 755종)
const ALL_COMBINED = [
    ...LUNCH_MENUS,
    ...DINNER_MENUS,
    ...LATE_NIGHT_MENUS,
    ...BREAKFAST_MENUS
];

module.exports = {
    name: 'menu',
    group: 'menu',
    icon: '🍱',
    aliases: ['!점심', '!점메추', '!저녁', '!저메추', '!메뉴', '!야식', '!아침'],
    description: '점심/저녁/야식/아침 상황별 750+종 음식 추천',

    web: {
        title: '오늘의 메뉴',
        icon: '🍽️',
        description: '오늘의 점심/저녁 메뉴 랜덤 추천 모듈 (750+종)',
        category: 'Commands',
        badge: 'Command'
    },

    async execute({ cmd, args, displayName, _input, ctx }) {
        const rawArg = (args && args.length > 0 && typeof args[0] === 'string')
            ? args.join(' ').trim()
            : '';
        const name = maskProfanity(displayName || '시청자');
        const cooldownMsg = ctx.getCooldownMsg(cmd);

        ctx.setCooldown(cmd, 0, _input);

        let timeLabel = '메뉴';
        let targetPool = LUNCH_MENUS; // 기본값

        // 1. 명령어별 시간대/목적 풀 매핑
        if (cmd.includes('점심') || cmd.includes('점메추')) {
            timeLabel = '점심';
            targetPool = LUNCH_MENUS;
        } else if (cmd.includes('저녁') || cmd.includes('저메추')) {
            timeLabel = '저녁';
            targetPool = DINNER_MENUS;
        } else if (cmd.includes('야식')) {
            timeLabel = '야식';
            targetPool = LATE_NIGHT_MENUS;
        } else if (cmd.includes('아침')) {
            timeLabel = '아침';
            targetPool = BREAKFAST_MENUS;
        } else {
            // !메뉴 일 때 현재 시간(KST) 기준 자동 판별
            const nowHour = new Date(Date.now() + 9 * 3600000).getUTCHours();
            if (nowHour >= 6 && nowHour < 11) {
                timeLabel = '아침';
                targetPool = BREAKFAST_MENUS;
            } else if (nowHour >= 11 && nowHour < 16) {
                timeLabel = '점심';
                targetPool = LUNCH_MENUS;
            } else if (nowHour >= 16 && nowHour < 22) {
                timeLabel = '저녁';
                targetPool = DINNER_MENUS;
            } else {
                timeLabel = '야식';
                targetPool = LATE_NIGHT_MENUS;
            }
        }

        // 2. 인자(카테고리/키워드) 필터링
        if (rawArg) {
            const cleanArg = rawArg.toLowerCase();
            const filtered = targetPool.filter(item =>
                (item.cat && item.cat.toLowerCase().includes(cleanArg)) ||
                item.name.toLowerCase().includes(cleanArg) ||
                (item.desc && item.desc.toLowerCase().includes(cleanArg))
            );

            if (filtered.length > 0) {
                targetPool = filtered;
            } else {
                // 현재 시간대 풀에 없으면 전체 풀에서 키워드 검색
                const globalFiltered = ALL_COMBINED.filter(item =>
                    (item.cat && item.cat.toLowerCase().includes(cleanArg)) ||
                    item.name.toLowerCase().includes(cleanArg) ||
                    (item.desc && item.desc.toLowerCase().includes(cleanArg))
                );
                if (globalFiltered.length > 0) {
                    targetPool = globalFiltered;
                }
            }
        }

        // 랜덤 1개 추첨
        const picked = targetPool[Math.floor(Math.random() * targetPool.length)];

        if (timeLabel === '점심' && msg.menu && msg.menu.lunch) {
            return msg.menu.lunch(name, picked.name, picked.desc, cooldownMsg);
        }
        if (timeLabel === '저녁' && msg.menu && msg.menu.dinner) {
            return msg.menu.dinner(name, picked.name, picked.desc, cooldownMsg);
        }
        if (msg.menu && msg.menu.general) {
            return msg.menu.general(timeLabel, name, picked.name, picked.desc, cooldownMsg);
        }

        return `🍴 [${timeLabel} 추천] ${name}님, 오늘의 ${timeLabel} 메뉴는 "${picked.name}" 어떠세요? (${picked.desc}) ${cooldownMsg}`;
    }
};
